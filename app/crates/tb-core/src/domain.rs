//! Plain data types shared across the core and serialised to the UI.

use serde::{Deserialize, Serialize};

/// Everything needed to interpret one data channel. The device is the source
/// of truth: this is read from it at connection time and after every change.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ChannelDescriptor {
    pub id: u8,
    /// `protocol::ids::sensor` code.
    pub sensor_type: u8,
    pub unit: u8,
    pub enabled: bool,
    pub invert: bool,
    /// False while the channel still uses nominal (uncalibrated) values.
    pub calibrated: bool,
    pub rate_hz: u16,
    pub gain: u8,
    /// Raw counts at zero load.
    pub offset: i32,
    /// Raw counts per engineering unit.
    pub scale: f32,
    /// Unix time of the last calibration, 0 when never calibrated.
    pub cal_time: u32,
    pub name: String,
}

impl ChannelDescriptor {
    /// Converts raw counts to the channel's engineering unit.
    pub fn to_engineering(&self, raw: i32) -> f64 {
        let value = (raw as f64 - self.offset as f64) / self.scale as f64;
        if self.invert {
            -value
        } else {
            value
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DeviceInfo {
    pub protocol_version: u8,
    pub firmware: String,
    pub uid: u32,
    pub channel_count: u8,
    pub capabilities: u16,
    /// The EEPROM was empty or corrupt at boot, so compiled defaults are in use.
    pub defaults_loaded: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ActuatorState {
    Disarmed,
    Armed,
    /// Latched emergency stop; must be cleared explicitly.
    EStop,
    /// The device watchdog cut the throttle because the host went silent.
    Failsafe,
}

impl ActuatorState {
    pub fn from_code(code: u8) -> Option<Self> {
        match code {
            0 => Some(Self::Disarmed),
            1 => Some(Self::Armed),
            2 => Some(Self::EStop),
            3 => Some(Self::Failsafe),
            _ => None,
        }
    }

    pub fn code(self) -> u8 {
        match self {
            Self::Disarmed => 0,
            Self::Armed => 1,
            Self::EStop => 2,
            Self::Failsafe => 3,
        }
    }
}

/// Periodic health report from the device (10 Hz).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DeviceStatus {
    pub actuator: ActuatorState,
    pub streaming: bool,
    pub config_dirty: bool,
    pub defaults_loaded: bool,
    pub tx_overflow: bool,
    /// Applied throttle, 0..1.
    pub throttle: f64,
    pub pulse_us: u16,
    pub tx_dropped: u16,
    pub crc_errors: u16,
    pub loop_max_us: u16,
    pub watchdog_trips: u8,
    pub uptime_ms: u32,
}

/// One calibrated measurement.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct Sample {
    pub channel: u8,
    /// Seconds on the device clock since the session started.
    pub t: f64,
    pub raw: i32,
    pub value: f64,
}

/// How the ESC throttle is commanded.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum DriverKind {
    /// PWM generated by the acquisition board; same clock as the sensors.
    NanoPwm,
    /// MAVLink actuator test through a PX4 flight controller (experimental).
    Mavlink,
    /// The operator drives the ESC with other equipment; the app only records.
    Manual,
}
