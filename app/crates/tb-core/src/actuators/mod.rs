//! Ways of commanding the ESC throttle.
//!
//! The bench service talks to a `ThrottleDriver` and does not care which one
//! is behind it. To add another (for example DShot through a different
//! board), implement the trait and add a `DriverKind`.

pub mod mavlink;

use crate::device::SessionHandle;
use crate::domain::{ActuatorState, DriverKind};
use crate::error::{Error, Result};

pub trait ThrottleDriver: Send {
    fn kind(&self) -> DriverKind;

    /// False for drivers that only observe (manual mode).
    fn can_command(&self) -> bool;

    fn arm(&mut self) -> Result<()>;

    fn disarm(&mut self) -> Result<()>;

    /// Throttle as a fraction 0..1. Only valid while armed.
    fn set_throttle(&mut self, fraction: f64) -> Result<()>;

    /// Must not block and must not fail.
    fn estop(&mut self);

    fn clear_estop(&mut self) -> Result<()>;

    /// Called about 50 times a second for keep-alives and housekeeping.
    fn tick(&mut self) -> Result<()> {
        Ok(())
    }

    /// Actuator state when the driver, not the acquisition board, owns it.
    /// `None` means "use the state reported by the board".
    fn state(&self) -> Option<ActuatorState> {
        None
    }
}

/// PWM generated by the acquisition board. Arming, watchdog, ceiling and
/// emergency stop are enforced by the firmware.
pub struct NanoPwmDriver {
    session: SessionHandle,
}

impl NanoPwmDriver {
    pub fn new(session: SessionHandle) -> Self {
        Self { session }
    }
}

impl ThrottleDriver for NanoPwmDriver {
    fn kind(&self) -> DriverKind {
        DriverKind::NanoPwm
    }

    fn can_command(&self) -> bool {
        true
    }

    fn arm(&mut self) -> Result<()> {
        self.session.arm()
    }

    fn disarm(&mut self) -> Result<()> {
        self.session.disarm()
    }

    fn set_throttle(&mut self, fraction: f64) -> Result<()> {
        self.session.set_throttle(fraction)
    }

    fn estop(&mut self) {
        self.session.estop();
    }

    fn clear_estop(&mut self) -> Result<()> {
        self.session.clear_estop()
    }
}

/// The operator drives the ESC with other equipment (servo tester, radio).
/// The application records but never commands.
pub struct ManualDriver;

impl ThrottleDriver for ManualDriver {
    fn kind(&self) -> DriverKind {
        DriverKind::Manual
    }

    fn can_command(&self) -> bool {
        false
    }

    fn arm(&mut self) -> Result<()> {
        Err(Error::Safety("manual mode cannot arm: the ESC is not controlled by this application".into()))
    }

    fn disarm(&mut self) -> Result<()> {
        Ok(())
    }

    fn set_throttle(&mut self, _fraction: f64) -> Result<()> {
        Err(Error::Safety("manual mode cannot command the throttle".into()))
    }

    fn estop(&mut self) {}

    fn clear_estop(&mut self) -> Result<()> {
        Ok(())
    }

    fn state(&self) -> Option<ActuatorState> {
        Some(ActuatorState::Disarmed)
    }
}
